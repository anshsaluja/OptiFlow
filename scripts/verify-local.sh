#!/usr/bin/env bash
# Reproducible local integration gate. Run with: bash scripts/verify-local.sh
set -Eeuo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

for command in sbt node npm python3; do
  if ! command -v "$command" >/dev/null 2>&1; then
    printf 'Missing prerequisite: %s\n' "$command" >&2
    exit 127
  fi
done

# Remove only known generated artifacts before invoking producers. Otherwise a stale
# report can make a broken CLI look successful when previous output remains.
mkdir -p output/scenarios
rm -f output/allocation.json output/scenarios/manifest.json output/scenario-impact.csv
rm -f output/scenarios/baseline.json
for snapshot in output/scenarios/scenario-{01..30}.json; do
  rm -f "$snapshot"
done

echo '[1/6] Scala optimizer tests'
sbt test
echo '[2/6] Generate allocation report'
sbt "runMain optiflow.AllocationReportCli datasets/demo output/allocation.json"
echo '[3/6] Generate scenario reports'
sbt "runMain optiflow.ScenarioSnapshotCli datasets/demo output/scenarios"
test -s output/allocation.json
test -s output/scenarios/manifest.json
test -s output/scenarios/baseline.json
# Check that the manifest and every referenced report were actually generated.
python3 - <<'PY'
import json
from pathlib import Path

root = Path("output/scenarios")
manifest = json.loads((root / "manifest.json").read_text(encoding="utf-8"))
scenarios = manifest["scenarios"]
assert isinstance(scenarios, list) and scenarios, "No scenarios generated"
for filename in [manifest["baseline"], *(item["report"] for item in scenarios)]:
    assert isinstance(filename, str) and Path(filename).name == filename, filename
    report = root / filename
    assert report.is_file() and report.stat().st_size > 0, f"Missing report: {report}"
    data = json.loads(report.read_text(encoding="utf-8"))
    assert data["schemaVersion"] == 1, f"Unsupported schema: {report}"
    # Verify generated optimizer reports are usable, not just nonempty JSON.
    summary = data["summary"]
    warehouses = {w["id"]: w for w in data["warehouses"]}
    stores = {s["id"]: s for s in data["stores"]}
    assert warehouses and stores, f"Empty network: {report}"
    assert sum(s["demand"] for s in stores.values()) == summary["totalDemand"], report
    assert sum(s["unmet"] for s in stores.values()) == summary["unfulfilledUnits"], report
    assert summary["fulfilledUnits"] + summary["unfulfilledUnits"] == summary["totalDemand"], report
    assert sum(s["units"] for s in data["shipments"]) == summary["fulfilledUnits"], report
    for warehouse_id, warehouse in warehouses.items():
        outgoing = sum(s["units"] for s in data["shipments"] if s["warehouseId"] == warehouse_id)
        assert outgoing <= min(warehouse["inventory"], warehouse["outboundCapacity"]), report
    for store_id, store in stores.items():
        incoming = sum(s["units"] for s in data["shipments"] if s["storeId"] == store_id)
        assert incoming + store["unmet"] == store["demand"], report
    for shipment in data["shipments"]:
        assert shipment["warehouseId"] in warehouses and shipment["storeId"] in stores, report
# The overview is generated by a separate CLI; validate it as well.
overview = Path("output/allocation.json")
overview_data = json.loads(overview.read_text(encoding="utf-8"))
assert overview_data["schemaVersion"] == 1, "Unsupported overview schema"
assert overview_data["warehouses"] and overview_data["stores"], "Empty overview network"
print(f"Verified {len(scenarios) + 1} generated JSON reports")
PY

echo '[4/6] Dashboard static checks, tests and production build'
(
  cd dashboard
  npm install --no-package-lock --no-audit --no-fund
  npm run check
  npm test
  npm run build
)

echo '[5/6] Python analytics and orchestration unit tests'
# Keep the DuckDB dependency isolated from the developer's global Python.
# A temporary environment also avoids requiring an activated project venv.
PY_ENV="$(mktemp -d)"
cleanup_python_env() { rm -rf "$PY_ENV"; }
trap cleanup_python_env EXIT
python3 -m venv "$PY_ENV"
"$PY_ENV/bin/python" -m pip install --disable-pip-version-check 'duckdb>=1.1,<2'
"$PY_ENV/bin/python" -m unittest discover -s analytics -p 'test_*.py' -v
"$PY_ENV/bin/python" -m unittest discover -s airflow -p 'test_*.py' -v

echo '[6/6] Export scenario impact CSV with DuckDB'
"$PY_ENV/bin/python" analytics/scenario_analytics.py output/scenarios output/scenario-impact.csv
test -s output/scenario-impact.csv
echo 'PASS: optimizer reports, dashboard, Python checks and analytics export'
echo 'NOTE: Docker Compose startup and Airflow scheduler execution are separate checks.'
