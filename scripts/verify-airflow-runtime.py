#!/usr/bin/env python3
"""Verify the OptiFlow DAG with a real, installed Apache Airflow runtime.

Run from any directory after installing Airflow, Java 17, sbt, Node 20,
dashboard dependencies and DuckDB. This intentionally does not mock Airflow.
"""
from __future__ import annotations

import csv
import json
import math
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

DAG_ID = "optiflow_local_scenario_pipeline"
REPO = Path(__file__).resolve().parents[1]
DAG_FOLDER = REPO / "airflow" / "dags"
MANIFEST = REPO / "output" / "scenarios" / "manifest.json"
ANALYTICS = REPO / "output" / "scenario-impact.csv"


def run(args: list[str], env: dict[str, str]) -> None:
    print("+", " ".join(args), flush=True)
    subprocess.run(args, cwd=REPO, env=env, check=True, timeout=2400)


def check_import_errors(env: dict[str, str]) -> None:
    """Treat DAG import errors as failures even when the CLI exits successfully."""
    args = ["airflow", "dags", "list-import-errors", "--output", "json"]
    print("+", " ".join(args), flush=True)
    result = subprocess.run(
        args, cwd=REPO, env=env, check=True, timeout=120,
        capture_output=True, text=True,
    )
    try:
        errors = json.loads(result.stdout)
    except json.JSONDecodeError as exc:
        raise RuntimeError(
            f"Airflow did not return valid import-error JSON: {result.stdout[:500]!r}"
        ) from exc
    if not isinstance(errors, list):
        raise RuntimeError(f"Unexpected Airflow import-error payload: {type(errors).__name__}")
    if errors:
        raise RuntimeError(f"Airflow DAG import errors: {json.dumps(errors)[:2000]}")


def signature(path: Path) -> tuple[int, int] | None:
    """Return mtime and size without treating an old artifact as fresh."""
    try:
        stat = path.stat()
    except FileNotFoundError:
        return None
    return stat.st_mtime_ns, stat.st_size


def main() -> int:
    missing = [tool for tool in ("airflow", "java", "sbt", "node", "npm")
               if shutil.which(tool) is None]
    if missing:
        print(f"Missing required executables: {', '.join(missing)}", file=sys.stderr)
        return 2
    try:
        import airflow  # noqa: F401
        import duckdb  # noqa: F401
    except ImportError as exc:
        print(f"Missing Python runtime dependency: {exc}", file=sys.stderr)
        return 2

    if not (REPO / "dashboard" / "node_modules").is_dir():
        print("Install dashboard dependencies: cd dashboard && npm install",
              file=sys.stderr)
        return 2

    previous_manifest = signature(MANIFEST)
    previous_analytics = signature(ANALYTICS)

    with tempfile.TemporaryDirectory(prefix="optiflow-airflow-") as home:
        env = {**os.environ,
               "AIRFLOW_HOME": home,
               "AIRFLOW__CORE__DAGS_FOLDER": str(DAG_FOLDER),
               "AIRFLOW__CORE__LOAD_EXAMPLES": "False",
               "OPTIFLOW_REPO_ROOT": str(REPO)}
        try:
            # A fresh metadata database avoids relying on a preexisting scheduler.
            run(["airflow", "db", "migrate"], env)
            check_import_errors(env)
            run(["airflow", "dags", "test", DAG_ID, "2026-11-14"], env)
        except (subprocess.CalledProcessError, subprocess.TimeoutExpired, RuntimeError) as exc:
            print(f"Real Airflow execution failed: {exc}", file=sys.stderr)
            return 1

    try:
        current_manifest = signature(MANIFEST)
        current_analytics = signature(ANALYTICS)
        if current_manifest is None or current_manifest == previous_manifest:
            raise RuntimeError("Scenario manifest was not regenerated by this DAG run")
        if current_analytics is None or current_analytics == previous_analytics:
            raise RuntimeError("Analytics CSV was not regenerated by this DAG run")
        manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
        if not isinstance(manifest, dict) or not isinstance(manifest.get("scenarios"), list) or not manifest["scenarios"]:
            raise RuntimeError("Scenario manifest must contain a nonempty scenarios list")
        expected = {}
        for entry in manifest["scenarios"]:
            if not isinstance(entry, dict):
                raise RuntimeError("Manifest scenario must be an object")
            scenario_id, label = entry.get("id"), entry.get("label")
            if not isinstance(scenario_id, str) or not scenario_id.strip():
                raise RuntimeError("Manifest scenario ID is missing")
            if not isinstance(label, str) or not label.strip():
                raise RuntimeError("Manifest scenario label is missing")
            scenario_id, label = scenario_id.strip(), label.strip()
            if scenario_id in expected:
                raise RuntimeError("Manifest contains duplicate scenario IDs")
            expected[scenario_id] = label

        required = {
            "id", "label", "optimized_cost", "cost_delta", "fulfilled",
            "shortage", "demand", "fulfillment_pct",
            "fulfilled_delta", "shortage_delta",
        }
        observed = set()
        with ANALYTICS.open(newline="", encoding="utf-8") as handle:
            reader = csv.DictReader(handle, strict=True)
            header = reader.fieldnames
            if not header or any(not column.strip() for column in header) or len(set(header)) != len(header):
                raise RuntimeError("Analytics CSV has missing or duplicate column names")
            if not required.issubset(header):
                raise RuntimeError("Analytics CSV missing required metric columns")
            for row in reader:
                if None in row or any(value is None for value in row.values()):
                    raise RuntimeError("Analytics CSV has inconsistent column counts")
                scenario_id = row["id"]
                if scenario_id not in expected or scenario_id in observed:
                    raise RuntimeError("Analytics CSV has unexpected or duplicate scenario IDs")
                if row["label"] != expected[scenario_id]:
                    raise RuntimeError("Analytics label does not match manifest")
                observed.add(scenario_id)
                quantities = {}
                for key in ("fulfilled", "shortage", "demand", "fulfilled_delta", "shortage_delta"):
                    value = row[key]
                    if not value or value.strip() != value:
                        raise RuntimeError(f"Invalid analytics integer metric: {key}")
                    try:
                        parsed = int(value)
                    except ValueError as exc:
                        raise RuntimeError(f"Invalid analytics integer metric: {key}") from exc
                    if str(parsed) != value or abs(parsed) > 2**53 - 1:
                        raise RuntimeError(f"Invalid analytics integer metric: {key}")
                    quantities[key] = parsed
                if any(quantities[key] < 0 for key in ("fulfilled", "shortage", "demand")):
                    raise RuntimeError("Analytics quantities must be nonnegative")
                if quantities["fulfilled"] + quantities["shortage"] != quantities["demand"]:
                    raise RuntimeError("Analytics fulfillment does not reconcile with demand")
                for key in ("optimized_cost", "cost_delta"):
                    try:
                        metric = float(row[key])
                    except ValueError as exc:
                        raise RuntimeError(f"Invalid analytics numeric metric: {key}") from exc
                    if not math.isfinite(metric) or (key == "optimized_cost" and metric < 0):
                        raise RuntimeError(f"Invalid analytics numeric metric: {key}")
                percentage = row["fulfillment_pct"]
                if quantities["demand"] == 0:
                    if percentage != "":
                        raise RuntimeError("Zero-demand fulfillment percentage must be empty")
                else:
                    try:
                        pct = float(percentage)
                    except ValueError as exc:
                        raise RuntimeError("Invalid fulfillment percentage") from exc
                    if not math.isfinite(pct) or not 0 <= pct <= 100:
                        raise RuntimeError("Invalid fulfillment percentage")
                    actual = round(100 * quantities["fulfilled"] / quantities["demand"], 2)
                    if abs(pct - actual) > 0.011:
                        raise RuntimeError("Fulfillment percentage does not reconcile")
        if observed != set(expected):
            raise RuntimeError("Analytics scenario IDs do not match manifest")

    except (OSError, UnicodeError, ValueError, csv.Error, RuntimeError) as exc:
        print(f"Output verification failed: {exc}", file=sys.stderr)
        return 1
    print(f"Real Airflow DAG succeeded: {len(manifest['scenarios'])} scenarios; "
          f"analytics at {ANALYTICS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
